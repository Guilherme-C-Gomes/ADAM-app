-- ADAM · ficha de matricula completa (a de papel, "Ficha de inscricao ADAM1").
--
-- Rodar no SQL Editor do projeto do ADAM (jmaztlceuandkyraazty). Pode rodar
-- de novo sem estragar nada.
--
-- Tudo o que a ficha de papel pede e nao cabe em `criancas`, `responsaveis`
-- e `documentos`: endereco, escola, familia, saude, quem assina e uso de
-- imagem (formato em src/data/ficha-matricula.ts). Uma linha por crianca,
-- com o NUMERO DE MATRICULA, que sai sozinho em ordem de cadastro.
-- So ADM e Secretaria leem e gravam, como o resto da ficha.

create table if not exists public.fichas_matricula (
  crianca_id uuid primary key references public.criancas (id) on delete cascade,
  numero bigint generated by default as identity unique,
  dados jsonb not null default '{}',
  atualizado_em timestamptz not null default now()
);

alter table public.fichas_matricula enable row level security;

drop policy if exists "matricula: ler" on public.fichas_matricula;
create policy "matricula: ler" on public.fichas_matricula
  for select to authenticated using (public.ve_dados_sensiveis());

drop policy if exists "matricula: cadastrar" on public.fichas_matricula;
create policy "matricula: cadastrar" on public.fichas_matricula
  for insert to authenticated with check (public.ve_dados_sensiveis());

drop policy if exists "matricula: editar" on public.fichas_matricula;
create policy "matricula: editar" on public.fichas_matricula
  for update to authenticated
  using (public.ve_dados_sensiveis())
  with check (public.ve_dados_sensiveis());

drop policy if exists "matricula: excluir" on public.fichas_matricula;
create policy "matricula: excluir" on public.fichas_matricula
  for delete to authenticated using (public.administra_secretaria());

revoke all on public.fichas_matricula from anon;

-- Toda crianca nova ja nasce com o numero de matricula.
create or replace function public.criar_ficha_matricula()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.fichas_matricula (crianca_id) values (new.id)
  on conflict (crianca_id) do nothing;
  return new;
end;
$$;

revoke execute on function public.criar_ficha_matricula() from public, anon, authenticated;

drop trigger if exists criar_ficha_matricula on public.criancas;
create trigger criar_ficha_matricula
  after insert on public.criancas
  for each row execute function public.criar_ficha_matricula();

-- As criancas que ja existem ganham o numero na ordem em que foram cadastradas.
insert into public.fichas_matricula (crianca_id)
select c.id from public.criancas c
where not exists (select 1 from public.fichas_matricula m where m.crianca_id = c.id)
order by c.criado_em, c.id;
